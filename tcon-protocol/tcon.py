def _mk_cbw(cbwcb, data_length, direction):
    """Build a 31-byte CBW for a 16-byte command block."""
    cbw = bytearray(31)
    cbw[0:4] = b'USBC'
    struct.pack_into('<I', cbw, 4, random.randint(0, 0xFFFFFFFF))
    struct.pack_into('<I', cbw, 8, data_length)
    cbw[12] = 0x80 if direction == 'in' else 0x00
    cbw[13] = 0
    cbw[14] = len(cbwcb)
    cbw[15:31] = cbwcb
    return bytes(cbw)


class Tcon:
    def __init__(self):
        self.log = logging.getLogger('tcon')
        self.dev = None

    def connect(self):
        self.dev = usb.core.find(idVendor=VID, idProduct=PID)
        if self.dev is None:
            raise RuntimeError("T-CON not found (VID 048d PID 8957)")
        if self.dev.is_kernel_driver_active(INTERFACE):
            self.dev.detach_kernel_driver(INTERFACE)
        usb.util.claim_interface(self.dev, INTERFACE)
        self.log.info("connected to T-CON")

    def disconnect(self):
        if self.dev:
            try:
                usb.util.release_interface(self.dev, INTERFACE)
                self.dev.attach_kernel_driver(INTERFACE)
            except Exception:
                pass
            usb.util.dispose_resources(self.dev)
            self.dev = None

    def _bulk(self, cbwcb, data=b'', direction='out', data_length=None):
        """CBW -> data phase -> CSW."""
        if data_length is None:
            data_length = len(data)
        cbw = _mk_cbw(cbwcb, data_length, direction)
        self.dev.write(EP_OUT, cbw, TIMEOUT)
        if direction == 'in':
            r = bytes(self.dev.read(EP_IN, data_length, TIMEOUT))
        else:
            if data:
                self.dev.write(EP_OUT, data, TIMEOUT)
            r = b''
        csw = bytes(self.dev.read(EP_IN, 13, TIMEOUT))
        if csw[0:4] != b'USBS':
            raise IOError(f"bad CSW signature: {csw.hex()}")
        if csw[12] != 0:
            raise IOError(f"CSW status error: 0x{csw[12]:02x}")
        return r

    def mailbox_out(self, payload):
        return self._bulk(CBWCB_MAILBOX_OUT, payload, 'out')

    def mailbox_in(self):
        return self._bulk(CBWCB_MAILBOX_IN, b'', 'in', data_length=4)

    def read_reg(self):
        return self._bulk(CBWCB_STATUS_POLL, b'', 'in', data_length=4)

    def enable_eink(self):
        for i, p in enumerate(ENABLE_EINK, 1):
            self.mailbox_out(p)
            time.sleep(0.05)
        time.sleep(1.0)
        self.log.info("enable-eink complete (12 payloads)")

    def write_chunk(self, index, data):
        addr = BUF_UPLOAD + index * CHUNK_SIZE
        cbwcb = (bytes([0xFE, 0x00])
                 + struct.pack('>I', addr)
                 + bytes([0xA5])
                 + struct.pack('>H', len(data))
                 + bytes(7))
        self._bulk(cbwcb, data, 'out')

    def show_buffer1(self):
        self.mailbox_out(SHOW_BUF1)
        self.log.info("show-buf1 sent (0x34 -> buffer 1)")


def _read_image(path):
    from PIL import Image
    im = Image.open(path).convert('L').resize((2560, 1600))
    return im.tobytes()


def main():
    logging.basicConfig(level=logging.INFO,
                        format='%(asctime)s %(levelname)s %(message)s')
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'status'
    t = Tcon()
    t.connect()
    try:
        if cmd == 'status':
            print('status reg:', t.read_reg().hex(' '))
        elif cmd == 'enable':
            t.enable_eink()
        elif cmd == 'chunk1':
            t.enable_eink()
            t.write_chunk(0, bytes(CHUNK_SIZE))
            print('chunk 0 written (zeroed)')
            print('status reg:', t.read_reg().hex(' '))
        elif cmd == 'show-buf1':
            t.show_buffer1()
        elif cmd == 'upload':
            if len(sys.argv) < 3:
                print('usage: tcon.py upload IMAGE')
                sys.exit(1)
            raw = _read_image(sys.argv[2])
            t.enable_eink()
            for i in range(TOTAL_CHUNKS):
                sz = LAST_CHUNK_SIZE if i == TOTAL_CHUNKS - 1 else CHUNK_SIZE
                off = i * CHUNK_SIZE
                t.write_chunk(i, raw[off:off + sz])
                print(f'chunk {i + 1}/{TOTAL_CHUNKS}')
            print('upload done — sending 0x34 display trigger (buffer 1)')
            t.show_buffer1()
            time.sleep(2.0)
            print('status reg:', t.read_reg().hex(' '))
        else:
            print('unknown command:', cmd)
            sys.exit(1)
    finally:
        t.disconnect()


if __name__ == '__main__':
    main()

